void print_message(string mess) // for messages to user
{
    if(parameters.verbosity>=0)
    {
        cout << "\n " << setfill('=') << setw(100) << "=" << endl;
        cout << " || " << mess << endl;
        cout << " " << setfill('=') << setw(100) << "=" << endl << endl;
    }
    
    return;
}

